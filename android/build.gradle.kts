// Some plugins (e.g. receive_sharing_intent) apply their own Kotlin Gradle
// Plugin without pinning a JVM target, so Kotlin defaults to the JDK running
// Gradle (21) while AGP compiles their Java to 11, which fails the build with an
// "Inconsistent JVM-target compatibility" error. Pin both compilers to 17 in
// every module so each one has a single, consistent JVM target. The Java target
// must go through AGP's compileOptions; AGP ignores it when set on the raw
// JavaCompile task.
subprojects {
    plugins.withId("com.android.library") {
        extensions.configure<com.android.build.api.dsl.LibraryExtension> {
            compileOptions {
                sourceCompatibility = JavaVersion.VERSION_17
                targetCompatibility = JavaVersion.VERSION_17
            }
        }
    }
    tasks.withType<org.jetbrains.kotlin.gradle.tasks.KotlinCompile>().configureEach {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17)
        }
    }
}

